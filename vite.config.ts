import { defineConfig } from "vite";
import { fileURLToPath } from "url";
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "path";
import { viteStaticCopy } from "vite-plugin-static-copy";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const figletFonts = JSON.parse(readFileSync(new URL("./figlet-fonts.json", import.meta.url), "utf8")) as string[];

export default defineConfig({
  plugins: [
    {
      name: "theme-runtime-assets",
      writeBundle(_options, bundle) {
        const stylesheet = bundle["main.css"];
        const script = bundle["main.iife.js"];
        if (stylesheet?.type !== "asset" || script?.type !== "chunk") {
          throw new Error("Cannot version the theme assets because the main stylesheet or script is missing.");
        }
        const revision = (content: string | Uint8Array) =>
          createHash("sha256").update(content).digest("hex").slice(0, 12);
        writeFileSync(
          new URL("./templates/modules/runtime-assets.html", import.meta.url),
          `<!-- Generated by the Vite build. -->
<link
  th:fragment="stylesheet"
  rel="stylesheet"
  th:href="@{/assets/main.css(v=\${theme.spec.version},r='${revision(stylesheet.source)}')}"
/>
<script th:fragment="script" th:src="@{/assets/main.iife.js(v=\${theme.spec.version},r='${revision(script.code)}')}" defer></script>
`,
        );
      },
    },
    viteStaticCopy({
      targets: [
        {
          src: "src/images/*",
          dest: "images",
          rename: { stripBase: true },
        },
        ...figletFonts.map((font) => ({
          src: `node_modules/figlet/fonts/${font}.flf`,
          dest: "fonts",
          rename: { stripBase: true },
        })),
      ],
    }),
  ],
  build: {
    outDir: fileURLToPath(new URL("./templates/assets", import.meta.url)),
    emptyOutDir: true,
    lib: {
      entry: path.resolve(__dirname, "src/main.ts"),
      name: "main",
      fileName: "main",
      formats: ["iife"],
    },
  },
});
